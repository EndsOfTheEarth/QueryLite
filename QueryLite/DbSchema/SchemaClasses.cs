namespace QueryLite.DbSchema; 

public sealed class DatabaseSchema(List<DatabaseTable> tables) {

    public List<DatabaseTable> Tables { get; } = tables;
}

public sealed class DatabaseTable(SchemaName schema, TableName name, bool isView) {

    public SchemaName Schema { get; } = schema;
    public TableName TableName { get; } = name;
    public bool IsView { get; } = isView;
    public string Description { get; set; } = "";
    public List<DatabaseColumn> Columns { get; } = [];

    public DatabasePrimaryKey? PrimaryKey { get; set; }
    public List<DatabaseUniqueConstraint> UniqueConstraints { get; } = [];
    public List<DatabaseCheckConstraint> CheckConstraints { get; } = [];
    public List<DatabaseForeignKey> ForeignKeys { get; } = [];

    public override string ToString() {
        return $"{Schema}.{TableName}";
    }
}

public sealed class DatabaseUniqueConstraint(string constraintName) {

    public string ConstraintName { get; } = constraintName;
    public List<ColumnName> ColumnNames { get; } = [];
}

public sealed class DatabaseCheckConstraint(string constraintName, string definition) {

    public string ConstraintName { get; } = constraintName;
    public string Definition { get; } = definition;
}

public sealed class DatabasePrimaryKey(string constraintName) {

    public string ConstraintName { get; } = constraintName;
    public List<string> ColumnNames { get; } = [];
}

public sealed class DatabaseColumn(DatabaseTable table, ColumnName name, DataType dataType,
                                   string sqlDataTypeName, ColumnLength? length, bool isNullable,
                                   bool isAutoGenerated) {

    public DatabaseTable Table { get; } = table;
    public ColumnName ColumnName { get; } = name;
    public DataType DataType { get; } = dataType;
    public string SqlDataTypeName { get; } = sqlDataTypeName;
    public bool IsPrimaryKey { get; internal set; }
    public ColumnLength? Length { get; } = length;
    public bool IsNullable { get; } = isNullable;
    public string Description { get; set; } = "";

    public bool IsAutoGenerated { get; } = isAutoGenerated;

    public override string ToString() {
        return $"{Table.TableName}.{ColumnName} ({(DataType?.ToString() ?? "?")})";
    }
}

public sealed class DatabaseForeignKey(string constraintName, DatabaseTable foreignKeyTable) {

    public string ConstraintName { get; } = constraintName;
    public DatabaseTable ForeignKeyTable { get; } = foreignKeyTable;
    public List<DatabaseForeignKeyReference> References { get; } = [];
}

public sealed class DatabaseForeignKeyReference(DatabaseColumn foreignKeyColumn,
                                                DatabaseColumn primaryKeyColumn) {

    public DatabaseColumn ForeignKeyColumn { get; } = foreignKeyColumn;
    public DatabaseColumn PrimaryKeyColumn { get; } = primaryKeyColumn;
}

public sealed class DataType(string name, Type dotNetType) {

    public string Name { get; } = name;
    public Type DotNetType { get; } = dotNetType;

    public override string ToString() {
        return $"{Name} {{{DotNetType}}}";
    }
}